"""Extract glyph outlines for the 3D CLAUDE letters and the Claude symbol path.

Writes src/glyphs.js: SVG path data in em units (y up), advance widths and the
Claude symbol path (24 x 24 viewBox, y down, from simple-icons).
Run: python3 tools/glyphs.py
"""
import json
import re
from pathlib import Path

from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.ttLib import TTFont

HERE = Path(__file__).parent
ROOT = HERE.parent
FONT = TTFont(HERE / "inter-tight-latin-700-normal.woff")
UPM = FONT["head"].unitsPerEm
cmap = FONT.getBestCmap()
gs = FONT.getGlyphSet()

glyphs = {}
for ch in "CLAUDE":
    name = cmap[ord(ch)]
    pen = SVGPathPen(gs)
    gs[name].draw(pen)
    glyphs[ch] = {"d": pen.getCommands(), "adv": FONT["hmtx"][name][0] / UPM}

svg = (ROOT / "assets" / "claude-symbol.svg").read_text()
symbol = re.search(r'<path d="([^"]+)"', svg).group(1)

out = (
    "// Generated by tools/glyphs.py. Inter Tight 700 outlines (font units, y up) and the Claude symbol.\n"
    f"export const UPM = {UPM};\n"
    f"export const GLYPHS = {json.dumps(glyphs)};\n"
    f"export const SYMBOL_PATH = {json.dumps(symbol)};\n"
)
(ROOT / "src" / "glyphs.js").write_text(out)
print("src/glyphs.js", len(out), "bytes, upm", UPM, {k: round(v["adv"], 3) for k, v in glyphs.items()})
